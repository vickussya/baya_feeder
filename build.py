def run_checks(parts):
    L = []                     # markdown lines
    ok_all = True

    def line(s=""):
        L.append(s)

    def check(name, cond, detail):
        nonlocal ok_all
        ok_all &= bool(cond)
        line(f"| {'PASS' if cond else '**FAIL**'} | {name} | {detail} |")

    line("# Design checks (generated by build.py - do not edit by hand)\n")
    line(f"Parameters: wheel {f.wheel_od:.0f} mm x {f.wheel_w:.0f} mm, {f.n_pockets} pockets, "
         f"bowl {f.bowl_diameter:.0f} x {f.bowl_depth:.0f} mm, chute {f.chute_angle:.0f} deg\n")

    # ---- dosing --------------------------------------------------------------
    wheel = parts["04_pocket_wheel"]
    pocket_ml = f.pocket_volume_ml(wheel)
    pocket_g = pocket_ml * f.bulk_density
    line("## Dosing\n")
    line(f"* Pocket volume (computed from the wheel solid, incl. fillets): **{pocket_ml:.2f} ml** "
         f"(sharp-edged sector solid: {f.vol_ml(f.pocket_prism(f.R_w)):.2f} ml)")
    line(f"* Grams per pocket at {f.bulk_density} g/ml: **{pocket_g:.2f} g**")
    for g in (f.dose_min_g, f.dose_default_g, f.dose_max_g):
        n = round(g / pocket_g)
        line(f"* Dose {g:.0f} g -> {n} pockets = {n * pocket_g:.1f} g  ({n * 360 // f.n_pockets} deg of wheel rotation)")
    pockets_default = round(f.dose_default_g / pocket_g)
    mouth = 2 * f.R_w * math.sin(math.radians(180 / f.n_pockets)) - f.pocket_web
    line(f"* Pocket mouth (tangential) = {mouth:.1f} mm = {mouth / f.pellet_diameter:.1f} x pellet diameter "
         f"(requirement >= 3x); axial width {f.pocket_w:.0f} mm = {f.pocket_w / f.pellet_diameter:.1f}x")
