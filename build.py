def main(render=True):
    os.makedirs(STL_DIR, exist_ok=True)
    os.makedirs(DOC_DIR, exist_ok=True)
    t0 = time.time()
    stl_info = {}
    parts = f.build_all()
    print(f"built {len(parts)} parts in {time.time() - t0:.1f}s")
    for name, shape in parts.items():
        assert shape.isValid(), name + " is not a valid solid"
        assert len(shape.Solids()) >= 1
        p = os.path.join(STL_DIR, name + ".stl")
        f.export_stl(f.to_print(name, shape), p)
        stl_info[name] = finalize_stl(p)
    print(f"exported STL to {STL_DIR}")
    step_dir = os.path.join(HERE, "step")
    os.makedirs(step_dir, exist_ok=True)
    import cadquery as cq
    asm = cq.Assembly(name="rabbit_feeder")
    for name, shape in parts.items():                 # assembly pose, opens directly in FreeCAD
        cq.exporters.export(f.W(shape), os.path.join(step_dir, name + ".step"))
        asm.add(f.W(shape), name=name, color=cq.Color(*[c / 255 for c in COLORS[name]]))
    asm.save(os.path.join(step_dir, "rabbit_feeder_assembly.step"))
    print(f"exported STEP to {step_dir}")
    report, ok = run_checks(parts)
    rows = ["", "## STL validation (reloaded with trimesh)", "", "| result | file | triangles | volume (ml) | extents (mm) |", "|---|---|---|---|---|"]
    for name, i in stl_info.items():
        good = i["watertight"]
        ok &= good
        rows.append(f"| {'PASS' if good else '**FAIL**'} | stl/{name}.stl | {i['tris']} | {i['volume_ml']:.1f} | "
                    + " x ".join(f"{x:.1f}" for x in i["extents"]) + " |")
    report += "\n".join(rows) + "\n"
    with open(os.path.join(DOC_DIR, "checks.md"), "w", encoding="utf-8") as fh:
        fh.write(report)
    print(report)
    if render:
        size = render_assembly(parts, os.path.join(DOC_DIR, "assembly.png"))
        print("rendered docs/assembly.png", size)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(render="--no-render" not in sys.argv))
