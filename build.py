def tessellate(shape, tol=0.15, ang=0.2):
    verts, tris = shape.tessellate(tol, ang)
    v = np.array([[p.x, p.y, p.z] for p in verts], dtype=np.float64)
    t = np.array(tris, dtype=np.int64)
    return v, t


def camera_basis(az_deg, el_deg):
    """camera looks towards the origin from direction (az, el); returns right, up, forward"""
    az, el = math.radians(az_deg), math.radians(el_deg)
    pos = np.array([math.cos(el) * math.sin(az), -math.cos(el) * math.cos(az), math.sin(el)])
    fwd = -pos
    right = np.cross(fwd, [0, 0, 1.0])
    right /= np.linalg.norm(right)
    up = np.cross(right, fwd)
    return right, up, fwd


def render_view(meshes, az, el, width, ss=2, bg=(246, 247, 249), margin=40):
    right, up, fwd = camera_basis(az, el)
    allv = np.vstack([m[0] for m in meshes])
    cen = (allv.min(0) + allv.max(0)) / 2
    P = (allv - cen) @ np.stack([right, up, fwd], axis=1)
    xmin, xmax, ymin, ymax = P[:, 0].min(), P[:, 0].max(), P[:, 1].min(), P[:, 1].max()
    scale = (width * ss - 2 * margin * ss) / (xmax - xmin)
    H = int((ymax - ymin) * scale + 2 * margin * ss)
    Wd = width * ss
    img = np.zeros((H, Wd, 3), dtype=np.float32)
    img[:] = bg
    zbuf = np.full((H, Wd), -1e18)
    light1 = np.array([-0.45, -0.55, 0.70]); light1 /= np.linalg.norm(light1)
    light2 = np.array([0.7, 0.2, 0.3]); light2 /= np.linalg.norm(light2)
    for (v, t, col) in meshes:
        pv = (v - cen) @ np.stack([right, up, fwd], axis=1)
        sx = (pv[:, 0] - xmin) * scale + margin * ss
        sy = H - ((pv[:, 1] - ymin) * scale + margin * ss)
        dz = -pv[:, 2]                                         # larger = closer to camera
        col = np.array(col, dtype=np.float32)
        a, b, c = v[t[:, 0]], v[t[:, 1]], v[t[:, 2]]
        n = np.cross(b - a, c - a)
        ln = np.linalg.norm(n, axis=1)
        n = n / np.maximum(ln[:, None], 1e-12)
        facing = n @ (-fwd)
        n = np.where((facing < 0)[:, None], -n, n)             # two-sided
        shade = 0.30 + 0.62 * np.clip(n @ light1, 0, 1) + 0.28 * np.clip(n @ light2, 0, 1)
        shade = np.clip(shade, 0, 1.15)
        for k in range(len(t)):
            if ln[k] < 1e-9:
                continue
            i0, i1, i2 = t[k]
            x0, y0, x1, y1, x2, y2 = sx[i0], sy[i0], sx[i1], sy[i1], sx[i2], sy[i2]
            minx, maxx = int(max(0, math.floor(min(x0, x1, x2)))), int(min(Wd - 1, math.ceil(max(x0, x1, x2))))
            miny, maxy = int(max(0, math.floor(min(y0, y1, y2)))), int(min(H - 1, math.ceil(max(y0, y1, y2))))
            if maxx < minx or maxy < miny:
                continue
            den = (y1 - y2) * (x0 - x2) + (x2 - x1) * (y0 - y2)
            if abs(den) < 1e-12:
                continue
            gx, gy = np.meshgrid(np.arange(minx, maxx + 1) + 0.5, np.arange(miny, maxy + 1) + 0.5)
            w0 = ((y1 - y2) * (gx - x2) + (x2 - x1) * (gy - y2)) / den
            w1 = ((y2 - y0) * (gx - x2) + (x0 - x2) * (gy - y2)) / den
            w2 = 1 - w0 - w1
            m = (w0 >= -1e-6) & (w1 >= -1e-6) & (w2 >= -1e-6)
            if not m.any():
                continue
            zz = w0 * dz[i0] + w1 * dz[i1] + w2 * dz[i2]
            zs = zbuf[miny:maxy + 1, minx:maxx + 1]
            upd = m & (zz > zs)
            if upd.any():
                zs[upd] = zz[upd]
                img[miny:maxy + 1, minx:maxx + 1][upd] = np.clip(col * shade[k], 0, 255)
    im = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8))
    return im.resize((Wd // ss, H // ss), Image.LANCZOS)


